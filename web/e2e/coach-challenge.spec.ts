import { expect, test } from '@playwright/test'
test('BOG UI Coach Studio metadata and explicit current sharing fit each viewport', async ({ page }, info) => {
  await page.goto('/e2e/fixtures/coach-challenge.html')
  await page.getByLabel('Group').selectOption('1')
  await expect(page.getByText('Fictional pilot participant')).toBeVisible()
  await expect(page.getByText(/Check-in unavailable/)).toBeVisible()
  await expect(page.getByText(/\$100.00 reported/)).toHaveCount(0)
  await page.getByRole('button', { name: 'View help for Fictional pilot participant' }).click()
  await page.getByRole('button', { name: 'View shared progress' }).click()
  await expect(page.getByText(/\$100.00 reported/)).toBeVisible()
  await page.getByRole('button', { name: 'Synthetic revoke sharing' }).click()
  await page.getByRole('button', { name: 'Refresh shared items' }).click()
  await expect(page.getByRole('alert')).toContainText('Synthetic sharing revoked')
  await expect(page.getByText(/\$100.00 reported/)).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('synthetic-coach-private-view.png'), fullPage: true })
})
test('BOG UI fixed coarse report review and private export choices are explicit', async ({ page }) => {
  await page.goto('/e2e/fixtures/coach-challenge.html')
  await page.getByLabel('Group').selectOption('1')
  await page.getByText('Checkpoint reports', { exact: true }).click()
  await page.getByRole('button', { name: 'Review scheduled reports' }).click()
  await expect(page.getByRole('button', { name: 'Save reviewed Day 30 report' })).toBeDisabled()
  await page.getByRole('checkbox', { name: /I reviewed how privacy works/ }).check()
  await page.getByRole('button', { name: 'Save reviewed Day 30 report' }).click()
  await expect(page.getByText('Progress is hidden to protect people’s privacy.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Download this group report' })).toBeVisible()
  await page.getByText('Download your record', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /Include my optional feeling history/ })).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Download my record' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('BOG UI household roster identifies setup help and phone detail returns to list context', async ({ page }) => {
  await page.goto('/e2e/fixtures/coach-challenge.html')
  await page.getByRole('combobox', { name: 'Group', exact: true }).selectOption('2')
  await expect(page.getByText('Elena', { exact: true })).toBeVisible()
  await expect(page.getByText('Asked for help with an upload')).toBeVisible()
  await expect(page.getByText('Challenge check-ins & help')).toHaveCount(0)
  await expect(page.getByText('Checkpoint reports', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'View help for Elena' }).click()
  await expect(page.getByRole('button', { name: 'Back to people' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to people' }).click()
  await expect(page.getByRole('button', { name: 'View help for Elena' })).toBeFocused()
  for (const control of await page.locator('.coach-challenge button:visible, .coach-challenge select:visible').all()) {
    expect((await control.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
