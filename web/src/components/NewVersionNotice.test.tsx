// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { NewVersionNotice } from './NewVersionNotice'
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.useRealTimers(); vi.restoreAllMocks(); vi.resetAllMocks() })

it('quietly checks on focus, offers one prompt and reloads only when asked', async () => {
  const fetcher = vi.fn().mockResolvedValue({ ok: true, json: async () => ({ version: 'old' }) })
  vi.stubGlobal('fetch', fetcher)
  const reload = vi.fn()
  render(<NewVersionNotice currentVersion="old" reload={reload} />)
  await waitFor(() => expect(fetcher).toHaveBeenCalledOnce())
  expect(screen.queryByRole('button', { name: 'Reload' })).toBeNull()
  fetcher.mockResolvedValue({ ok: true, json: async () => ({ version: 'new' }) })
  fireEvent.focus(window)
  await screen.findByText('A newer version is ready.')
  expect(reload).not.toHaveBeenCalled()
  fireEvent.focus(window)
  await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(3))
  expect(screen.getAllByRole('status')).toHaveLength(1)
  expect(fetcher.mock.calls[0][1].cache).toBe('no-store')
  fireEvent.click(screen.getByRole('button', { name: 'Reload' }))
  expect(reload).toHaveBeenCalledOnce()
})
it('respects unsaved form guards and retains input and focus until she can reload', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, json: async () => ({ version: 'new' }) }))
  const reload = vi.fn()
  const guard = (event: Event) => event.preventDefault()
  window.addEventListener('beforeunload', guard)
  try {
    render(<><input aria-label="Unsent message" defaultValue="Keep my words" /><NewVersionNotice currentVersion="old" reload={reload} /></>)
    const field = screen.getByLabelText('Unsent message')
    field.focus()
    await screen.findByText('A newer version is ready.')
    expect(document.activeElement).toBe(field)
    fireEvent.click(screen.getByRole('button', { name: 'Reload' }))
    expect(reload).not.toHaveBeenCalled()
    expect(screen.getByText('Save or cancel your open changes, then reload.')).toBeTruthy()
    expect((field as HTMLInputElement).value).toBe('Keep my words')
    window.removeEventListener('beforeunload', guard)
    fireEvent.click(screen.getByRole('button', { name: 'Reload' }))
    expect(reload).toHaveBeenCalledOnce()
  } finally { window.removeEventListener('beforeunload', guard) }
})
it('retries offline and malformed responses on the interval, skips hidden tabs and cleans up', async () => {
  vi.useFakeTimers()
  const fetcher = vi.fn().mockRejectedValueOnce(new Error('Offline')).mockResolvedValue({ ok: true, json: async () => ({ version: 55 }) })
  vi.stubGlobal('fetch', fetcher)
  const view = render(<NewVersionNotice currentVersion="old" />)
  await act(async () => {})
  await act(async () => { await vi.advanceTimersByTimeAsync(5 * 60_000) })
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(screen.queryByRole('status')).toBeNull()
  vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
  fireEvent.focus(window)
  await act(async () => { await vi.advanceTimersByTimeAsync(5 * 60_000) })
  expect(fetcher).toHaveBeenCalledTimes(2)
  view.unmount()
  fireEvent.focus(window)
  await act(async () => { await vi.advanceTimersByTimeAsync(5 * 60_000) })
  expect(fetcher).toHaveBeenCalledTimes(2)
})
